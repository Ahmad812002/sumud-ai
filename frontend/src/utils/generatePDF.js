
import jsPDF from 'jspdf'



export function generateCoverLetterPDF(coverLetter, jobDescription){
    const doc = new jsPDF({
        orientation: 'portrait',
        unit: 'mm',
        format: 'a4'
    })

    const pageWidth = doc.internal.pageSize.getWidth()
    const margin = 20
    const contentWidth = pageWidth - margin * 2
    let y = 0

    // ── Header Bar ─────────────────────────────────────────
    doc.setTextColor(255, 255, 255)
    doc.setFontSize(16)
    doc.setFont('helvetica', 'bold')

    doc.setFontSize(9)
    doc.setFont('helvetica', 'normal')
    doc.text('sumud-ai.com', pageWidth - margin, 14, { align: 'right' })

    // ── Green accent line ───────────────────────────────────
    doc.setFillColor(0, 122, 61)  // Palestine green
    doc.rect(0, 22, pageWidth, 3, 'F')
    y = 38

    // ── Date ───────────────────────────────────────────────
    doc.setTextColor(120, 120, 120)
    doc.setFontSize(9)
    doc.setFont('helvetica', 'normal')
    const today = new Date().toLocaleDateString('en-GB', {
        day: 'numeric', month: 'long', year: 'numeric'
    })
    doc.text(today, pageWidth - margin, y, { align: 'right' })


    y += 12


    // ── Cover Letter Sections ───────────────────────────────
    const sections = [
        { label: null, content: coverLetter.opening },
        { label: null, content: coverLetter.middle },
        { label: null, content: coverLetter.gap },
        { label: null, content: coverLetter.closing },
    ]

    doc.setTextColor(26, 26, 26)
    doc.setFontSize(11)
    doc.setFont('helvetica', 'normal')


    sections.forEach((section) => {
        if (!section.content) return

        const lines = doc.splitTextToSize(section.content, contentWidth)
        const blockHeight = lines.length * 6

        // Page break if needed
        if (y + blockHeight > 270) {
            doc.addPage()
            y = 20
        }
        doc.text(lines, margin, y)
        y += blockHeight + 8  // paragraph spacing
    })


    // ── Footer ──────────────────────────────────────────────
    const pageHeight = doc.internal.pageSize.getHeight()
    doc.setFillColor(200, 16, 46)
    doc.rect(0, pageHeight - 12, pageWidth, 12, 'F')

    doc.setTextColor(255, 255, 255)
    doc.setFontSize(8)
    doc.setFont('helvetica', 'normal')
    doc.text('Generated by Sumud AI  ·  Be Sumud in your life  🇵🇸', pageWidth / 2, pageHeight - 4, { align: 'center' })

    // ── Save ────────────────────────────────────────────────
    const filename = `Cover_Letter_${new Date().toISOString().split('T')[0]}.pdf`
    doc.save(filename)
}

